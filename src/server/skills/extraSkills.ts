import type { SkillDefinition, Subskill } from "./catalog";

// Skills for every kind of student and profession (B.Tech, B.Com, BBA, MBA,
// creative, health, law…). Each gets its own teacher and a development
// framework built from its subskills.

const sub = (labels: string[]): Subskill[] =>
  labels.map((label) => ({ key: label.toLowerCase().replace(/[^a-z]+/g, "_").replace(/^_|_$/g, ""), label }));

function skill(
  slug: string,
  name: string,
  group: string,
  description: string,
  subskills: string[],
  teacher: [name: string, emoji: string, tagline: string, style: string],
  tags: string[] = [],
): SkillDefinition {
  const subs = sub(subskills);
  const lower = name.toLowerCase();
  return {
    slug,
    name,
    category: "specific",
    description,
    framework: {
      teacher: { name: teacher[0], emoji: teacher[1], title: `${name} coach`, tagline: teacher[2], style: teacher[3] },
      group,
      tags,
      subskills: subs,
      criteria: [
        `Practised ${lower} in a real situation, not just in theory`,
        "Shared specific details of what they did and what happened",
        "Applied what they learned from earlier attempts",
      ],
      categories: [`Small daily ${lower} practice`, "Use it in a real situation", "Get feedback from someone", "Stretch attempt"],
      progression: `Start with short, low-stakes practice of ${subs[0].label.toLowerCase()}, then use ${lower} in real situations, then take on harder, higher-stakes versions with feedback.`,
    },
  };
}

